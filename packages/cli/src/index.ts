hubCommand
  .command('create-token')
  .description('Provision a product-scoped ingest token for the Report Hub (requires a Postgres-backed Hub)')
  .requiredOption('-p, --product <id>', 'Product identifier to scope this token to')
  .option('-l, --label <label>', 'Human-readable label for this token', 'default')
  .option('--db <url>', 'Postgres connection string (overrides DATABASE_URL)')
  .action(async (options) => {
    const dbUrl = options.db || process.env.DATABASE_URL;
    if (!dbUrl) {
      console.error(
        pc.red(
          `A Postgres connection is required to provision a durable token (pass --db or set DATABASE_URL). An in-memory Hub cannot be provisioned from a separate process.`
        )
      );
      process.exit(1);
    }
    const db = new PostgresHubDatabase(dbUrl);
    const existing = await db.getProduct(options.product);
    if (!existing) {
      await db.createProduct({ id: options.product, name: options.product, createdAt: new Date().toISOString() });
    }
    const token = crypto.randomBytes(24).toString('hex');
    await db.createToken({ token, productId: options.product, label: options.label, createdAt: new Date().toISOString() });
    console.log(pc.green(`✔ Token created for product "${options.product}"`));
    console.log(`  ${pc.bold(token)}`);
    console.log(pc.gray(`\nUse it with: qa-test run ... --hub <url> --hub-token ${token}\n`));
  });

