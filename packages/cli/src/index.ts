// Command: verify
program
  .command('verify <findingId>')
  .description('Verify whether a specific finding has been fixed by re-running its test point')
  .option('-o, --output <dir>', 'Reports directory', '.qa-report')
  .option('-s, --spec <path>', 'Spec file path (optional, will attempt reading default or previous run)')
  .action(async (findingId, options) => {
    console.log(pc.cyan(`\n🔍 Verifying finding: ${findingId}`));
    const reportDir = options.output || '.qa-report';
    const findingsJsonPath = path.join(reportDir, 'findings.json');

    try {
      const content = await fs.readFile(findingsJsonPath, 'utf8');
      const report: ReleaseReport = JSON.parse(content);
      const finding = report.findings.find((f) => f.id === findingId);

      if (!finding) {
        console.error(pc.red(`Finding ${findingId} not found in ${findingsJsonPath}`));
        process.exit(1);
      }

      console.log(pc.bold(`Title:`), finding.title);
      console.log(pc.bold(`Checker:`), finding.checker);
      console.log(pc.bold(`Location:`), finding.where.urlPath);
      console.log(pc.bold(`Role:`), finding.where.role);
      console.log(pc.bold(`Breakpoint:`), finding.where.breakpoint);

      let targetTestCase: any;
      if (options.spec) {
        const specContent = await fs.readFile(options.spec, 'utf8');
        const parsed = options.spec.endsWith('.yaml') || options.spec.endsWith('.yml')
          ? parseYaml(specContent)
          : JSON.parse(specContent);
        targetTestCase = parsed.testCases?.find((t: any) => t.id === finding.testCaseId);
      }

      if (!targetTestCase) {
        // Fallback test case from finding information
        targetTestCase = {
          id: finding.testCaseId || 'TC-VERIFY',
          flowId: finding.flowId || 'verify-flow',
          name: `Verification for ${findingId}`,
          role: finding.where.role || 'anonymous',
          startPage: finding.where.urlPath,
          steps: [{ action: 'wait', name: 'Wait for page load' }],
          expectations: {
            url: { pattern: '/*' },
          },
        };
      }

      console.log(pc.gray(`Re-running test point ${targetTestCase.id}...`));
      const orchestrator = new FlowTestOrchestrator();
      const verifyReport = await orchestrator.run({
        targetUrl: report.targetUrl,
        productId: report.productId,
        specTestCases: [targetTestCase],
        outputDir: path.join(reportDir, '.verify-tmp'),
        breakpoints: [finding.where.breakpoint],
        repoRoot: process.cwd(),
      });

      // Check if this finding re-occurred
      const stillFailing = verifyReport.findings.some(
        (f) => f.title === finding.title && f.where.urlPath === finding.where.urlPath
      );

      if (!stillFailing) {
        console.log(pc.green(pc.bold(`\n✔ Finding ${findingId} verified as FIXED!`)));
        finding.triageStatus = 'Resolved';
        await fs.writeFile(findingsJsonPath, JSON.stringify(report, null, 2), 'utf8');

        // Update report.md
        const { ReportGenerator } = await import('@qa/core');
        const reportGen = new ReportGenerator(reportDir);
        await reportGen.generate(report);
        console.log(pc.gray(`Updated status to "Resolved" in ${findingsJsonPath} and report.md\n`));
      } else {
        console.log(pc.red(pc.bold(`\n✖ Finding ${findingId} STILL FAILS.`)));
        console.log(pc.yellow(`Expected: ${finding.expectedVsActual.expected}`));
        console.log(pc.yellow(`Resolution hint: ${finding.resolution}\n`));
        process.exit(1);
      }
    } catch (err: unknown) {
      console.error(pc.red(`Verification error:`), err instanceof Error ? err.message : err);
      process.exit(1);
    }
  });

