// Command: run
program
  .command('run')
  .description('Execute full pre-release readiness checks against a target URL')
  .requiredOption('-u, --url <url>', 'Target staging or tunnel URL (e.g. http://localhost:3000)')
  .option('-p, --product <id>', 'Product identifier', 'default-product')
  .option('-s, --spec <path>', 'Path to test case spec file (JSON or YAML)')
  .option('-c, --config <path>', 'Path to product profile config file')
  .option('--ai', 'Automatically discover flows using AI prior to execution')
  .option('--context <path>', 'Path to PRD / Product Context for AI discovery')
  .option('--ai-provider <provider>', 'AI provider (anthropic, openai, gemini, openrouter, mock)')
  .option('--api-key <key>', 'API key for AI provider')
  .option('--ai-model <model>', 'Override the default model used for AI discovery')
  .option('--tunnel-auth <token>', 'Dev tunnel authorization token')
  .option('--no-headless', 'Run browser in headed mode')
  .option('-o, --output <dir>', 'Output directory for reports', '.qa-report')
  .option('--dashboard', 'Open local review dashboard after test execution')
  .option('--dashboard-port <port>', 'Port for dashboard if --dashboard is enabled', '3000')
  .option('--all-breakpoints', 'Run checks across all breakpoints (375px, 768px, 1440px)')
  .option('--breakpoints <list>', 'Comma-separated breakpoints list (e.g. 375px,1440px)')
  .option('--hub <url>', 'Report Hub server URL (e.g. http://localhost:3001)')
  .option('--hub-token <token>', 'Product-scoped ingest token for Report Hub')
  .option('--release <target>', 'Release target name (e.g. v1.2.0-rc1)', 'latest')
  .option('--update-baselines', 'Save this run\'s final screens as the approved visual baselines instead of diffing')
  .option('--no-video', 'Do not record session video for failed test points')
  .action(async (options) => {
    console.log(pc.cyan(`\n🔍 QA Pre-Release Readiness Checker v0.3.0`));
    console.log(pc.gray(`Target: ${options.url} | Product: ${options.product}\n`));


    try {
      let profile: ProductProfile | undefined;
      if (options.config) {
        const cfgContent = await fs.readFile(options.config, 'utf8');
        profile = parseYaml(cfgContent);
      }

      let specTestCases = [];
      let usedFallbackDiscovery = false;

      if (options.ai) {
        console.log(pc.cyan(`\n🤖 Running AI Discovery Pipeline...`));
        const keyResolver = new KeyResolver();
        const resolved = await keyResolver.resolveKey(options.aiProvider, options.apiKey);
        const providerType: AIProviderType = resolved?.provider || options.aiProvider || 'mock';
        const apiKey = resolved?.apiKey || options.apiKey || 'mock-key';

        if (!resolved && providerType !== 'mock') {
          console.log(pc.yellow(`⚠️ No API key found for ${providerType}. Falling back to MockAIProvider.`));
        }

        const aiProvider = createAIProvider(providerType, apiKey, undefined, options.aiModel);
        const agent = new DiscoveryAgent();
        const draft = await agent.discover({
          targetUrl: options.url,
          productId: options.product,
          profile,
          contextFilePath: options.context,
          outputDir: options.output,
          aiProvider,
        });

        const planner = new TestPlanner();
        const generatedSpec = planner.plan(draft);
        specTestCases = generatedSpec.testCases;
        console.log(pc.green(`✔ AI generated ${specTestCases.length} test cases from ${draft.flows.length} flows.\n`));
        usedFallbackDiscovery = !!draft.usedFallbackSynthesis;
        if (usedFallbackDiscovery) {
          console.log(
            pc.yellow(
              `⚠️ AI discovery did not produce usable flows — test cases were generated by the generic template fallback, not real AI analysis. Findings below may not reflect the app's actual behavior.`
            )
          );
        }
      } else if (options.spec) {
        const specContent = await fs.readFile(options.spec, 'utf8');
        const parsed: SpecFile = options.spec.endsWith('.yaml') || options.spec.endsWith('.yml')
          ? parseYaml(specContent)
          : JSON.parse(specContent);
        specTestCases = parsed.testCases || [];
      } else {
        // Fallback default test case
        specTestCases = [
          {
            id: 'TC-DEFAULT-001',
            flowId: 'landing-verification',
            name: 'Home page sanity check',
            role: 'anonymous',
            startPage: '/',
            steps: [
              { action: 'wait' as const, name: 'Wait for page load' },
            ],
            expectations: {
              url: { pattern: '/*' },
            },
          },
        ];
      }

      let breakpoints: any = ['1440px'];
      if (options.allBreakpoints) {
        breakpoints = ['375px', '768px', '1440px'];
      } else if (options.breakpoints) {
        breakpoints = options.breakpoints.split(',').map((b: string) => b.trim());
      }

      const orchestrator = new FlowTestOrchestrator();
      const report: ReleaseReport = await orchestrator.run({
        targetUrl: options.url,
        productId: options.product,
        specTestCases,
        profile,
        headless: options.headless,
        tunnelAuth: options.tunnelAuth,
        outputDir: options.output,
        breakpoints,
        repoRoot: process.cwd(),
        recordVideo: options.video,
        updateBaselines: options.updateBaselines,
      });
      report.usedFallbackDiscovery = usedFallbackDiscovery;
      if (options.updateBaselines) {
        console.log(pc.cyan(`📸 Visual baselines updated in ${profile?.visualBaselineDir || '.qa-baselines'}`));
      }

      console.log(pc.green(`\n✔ QA Run completed in ${(report.durationMs / 1000).toFixed(1)}s`));
      console.log(pc.bold(`Findings: ${report.findings.length} total`));
      if (report.usedFallbackDiscovery) {
        console.log(
          pc.yellow(`⚠️ This run used the fallback test generator, not AI discovery — see report.md for details.`)
        );
      }
      
      const blockers = report.findings.filter((f) => f.severity === 'Blocker');
      if (blockers.length > 0) {
        console.log(pc.red(pc.bold(`✖ ${blockers.length} BLOCKERS FOUND! Release is NOT recommended.`)));
      } else {
        console.log(pc.green(pc.bold(`✔ Zero blockers found. Release ready!`)));
      }

      console.log(pc.cyan(`\nReports generated:`));
      console.log(`  📄 Markdown: ${path.join(options.output, 'report.md')}`);
      console.log(`  📊 JSON:     ${path.join(options.output, 'findings.json')}\n`);

      if (options.hub) {
        console.log(pc.cyan(`\n☁ Syncing run results to Report Hub (${options.hub})...`));
        const uploadRes = await pushRunToHub(report, {
          hubUrl: options.hub,
          hubToken: options.hubToken,
          outputDir: options.output,
          releaseTarget: options.release || 'latest',
        });
        if (uploadRes.synced) {
          console.log(pc.green(`✔ Run successfully consolidated into Report Hub!`));
          console.log(`  🌐 Hub URL: ${pc.bold(pc.underline(uploadRes.hubViewUrl || options.hub))}\n`);
        } else if (uploadRes.authFailed) {
          console.log(pc.red(`✖ Hub rejected this run: ${uploadRes.error}`));
          console.log(pc.gray(`  Provide a valid token with --hub-token, or provision one via: qa-test hub create-token --product ${options.product}\n`));
        } else if (uploadRes.queued) {
          console.log(pc.yellow(`⚠️ Hub temporarily unreachable. Run saved to local outbox (ID: ${uploadRes.outboxId}).`));
          console.log(pc.gray(`  Will auto-sync on next online run or via: qa-test hub sync --hub ${options.hub}\n`));
        }
      }

      if (options.dashboard) {
        const port = parseInt(options.dashboardPort, 10) || 3000;
        const server = new DashboardServer({
          port,
          reportDir: options.output,
        });
        const url = await server.start();
        console.log(pc.cyan(`\n🚀 Local Review Dashboard running at:`), pc.bold(pc.underline(url)));
        console.log(pc.gray(`Press Ctrl+C to stop the dashboard server.\n`));
      }

    } catch (err: unknown) {
      console.error(pc.red(`\n✖ Execution failed:`), err instanceof Error ? err.message : err);
      process.exit(1);
    }
  });

