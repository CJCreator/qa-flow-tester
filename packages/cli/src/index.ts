// Command: compare
program
  .command('compare')
  .description('Safely benchmark an internal product flow against an external public reference flow')
  .requiredOption('-t, --target <url>', 'Internal target staging / tunnel URL')
  .requiredOption('-r, --reference <url>', 'Public reference / competitor URL')
  .option('-f, --flow <id>', 'Flow identifier (e.g. onboarding, pricing, checkout)', 'onboarding')
  .option('-o, --output <dir>', 'Output directory for benchmark reports', '.qa-compare')
  .option('--ai-provider <provider>', 'AI provider for UX gap synthesis (anthropic, openai, gemini, mock)')
  .option('--api-key <key>', 'API key for AI provider')
  .option('--hub <url>', 'Report Hub server URL for uploading visual benchmark gallery')
  .action(async (options) => {
    console.log(pc.cyan(`\n⚡ QA Competitive Flow Benchmarking v0.4.0`));
    console.log(pc.gray(`Target:    ${options.target}`));
    console.log(pc.gray(`Reference: ${options.reference}`));
    console.log(pc.gray(`Flow:      ${options.flow}\n`));

    try {
      const crawler = new SafePublicCrawler();
      console.log(pc.cyan(`🔍 [1/4] Crawling our internal flow...`));
      const ourFlow = await crawler.crawl({
        entryUrl: options.target,
        flowName: 'Our Flow',
        outputDir: path.join(options.output, 'our'),
        // Our own staging sites commonly disallow all crawlers; robots.txt is for external sites.
        respectRobots: false,
      });

      console.log(pc.cyan(`🌐 [2/4] Crawling external reference flow in Safe Interaction Mode...`));
      const refFlow = await crawler.crawl({
        entryUrl: options.reference,
        flowName: 'Competitor Reference',
        outputDir: path.join(options.output, 'reference'),
      });

      console.log(pc.cyan(`📊 [3/4] Calculating multi-dimensional friction scorecards...`));
      const engine = new BenchmarkingEngine();
      const ourScore = engine.calculateScorecard(ourFlow);
      const refScore = engine.calculateScorecard(refFlow);

      console.log(pc.cyan(`🤖 [4/4] Synthesizing AI UX Gap Analysis...`));
      const keyResolver = new KeyResolver();
      const resolved = await keyResolver.resolveKey(options.aiProvider, options.apiKey);
      const providerType: AIProviderType = resolved?.provider || options.aiProvider || 'mock';
      const apiKey = resolved?.apiKey || options.apiKey || 'mock-key';
      const aiProvider = createAIProvider(providerType, apiKey);

      const synthesizer = new UXGapSynthesizer();
      const recommendations = await synthesizer.synthesize(
        ourFlow,
        refFlow,
        ourScore,
        refScore,
        aiProvider
      );

      const benchmark = engine.compareFlows(options.flow, ourFlow, refFlow, recommendations);

      // Save local artifacts
      await fs.mkdir(options.output, { recursive: true });
      const jsonPath = path.join(options.output, 'benchmark.json');
      await fs.writeFile(jsonPath, JSON.stringify(benchmark, null, 2), 'utf8');

      const mdPath = path.join(options.output, 'benchmark.md');
      const mdContent = `# Competitive Flow Benchmark: ${options.flow}

**Date**: ${new Date().toISOString()}  
**Target**: ${options.target}  
**Reference**: ${options.reference}  

## 1. Friction Scorecard Comparison

| Metric | Our Product | Competitor Reference | Delta |
| :--- | :--- | :--- | :--- |
| **Total Steps** | ${ourScore.totalSteps} | ${refScore.totalSteps} | ${benchmark.delta.stepDifference > 0 ? `+${benchmark.delta.stepDifference}` : benchmark.delta.stepDifference} |
| **Total Input Fields** | ${ourScore.totalFields} | ${refScore.totalFields} | ${benchmark.delta.fieldDifference > 0 ? `+${benchmark.delta.fieldDifference}` : benchmark.delta.fieldDifference} |
| **Required Fields** | ${ourScore.requiredFieldsCount} | ${refScore.requiredFieldsCount} | ${ourScore.requiredFieldsCount - refScore.requiredFieldsCount} |
| **Click Depth** | ${ourScore.clickDepth} | ${refScore.clickDepth} | ${ourScore.clickDepth - refScore.clickDepth} |
| **Friction Index** | **${ourScore.frictionIndex}** | **${refScore.frictionIndex}** | **${benchmark.delta.frictionRatio}x** |

## 2. Interactive Pattern Parity

| Pattern | Our Product | Competitor |
| :--- | :---: | :---: |
${benchmark.patterns.map((p) => `| ${p.pattern} | ${p.ourProduct ? '✔' : '✖'} | ${p.referenceProduct ? '✔' : '✖'} |`).join('\n')}

## 3. Prioritized UX Recommendations

${benchmark.recommendations.map((r, i) => `### ${i + 1}. [${r.category}] ${r.title}
- **Impact / Effort**: ${r.impact} Impact | ${r.effort} Effort
- **Rationale**: ${r.rationale}
- **Suggested Action**: ${r.suggestedAction}
`).join('\n')}
`;
      await fs.writeFile(mdPath, mdContent, 'utf8');

      // CLI Output summary
      console.log(pc.green(pc.bold(`\n✔ Competitive Benchmark Completed!`)));
      console.log(`\n┌────────────────────────┬─────────────┬─────────────┐`);
      console.log(`│ Metric                 │ Our Product │ Competitor  │`);
      console.log(`├────────────────────────┼─────────────┼─────────────┤`);
      console.log(`│ Total Steps            │ ${String(ourScore.totalSteps).padEnd(11)} │ ${String(refScore.totalSteps).padEnd(11)} │`);
      console.log(`│ Required Input Fields  │ ${String(ourScore.requiredFieldsCount).padEnd(11)} │ ${String(refScore.requiredFieldsCount).padEnd(11)} │`);
      console.log(`│ Friction Index         │ ${String(ourScore.frictionIndex).padEnd(11)} │ ${String(refScore.frictionIndex).padEnd(11)} │`);
      console.log(`└────────────────────────┴─────────────┴─────────────┘\n`);

      console.log(pc.cyan(`Reports saved:`));
      console.log(`  📄 Markdown: ${mdPath}`);
      console.log(`  📊 JSON:     ${jsonPath}\n`);

      if (options.hub) {
        console.log(pc.cyan(`☁ Uploading benchmark to Report Hub (${options.hub})...`));
        try {
          const res = await fetch(`${options.hub.replace(/\/+$/, '')}/api/v1/benchmarks`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(benchmark),
          });
          if (res.ok) {
            console.log(pc.green(`✔ Benchmark uploaded to Report Hub!`));
            console.log(`  🌐 View Comparison: ${pc.bold(pc.underline(`${options.hub}/compare?id=${benchmark.id}`))}\n`);
          }
        } catch {
          console.log(pc.yellow(`⚠️ Could not upload to Hub server.`));
        }
      }
    } catch (err: unknown) {
      console.error(pc.red(`\n✖ Benchmarking failed:`), err instanceof Error ? err.message : err);
      process.exit(1);
    }
  });

